package basic_of_java;

public class IncrementDecrement {
    static void main() {
       int abhi=23;
       abhi+=1;// post increment operator i++
        System.out.println(abhi);
        abhi-=1;//post decrement operator i--
        System.out.println(abhi);
        ++abhi;//pre increment
        --abhi;//pre decrement
        System.out.println(abhi);
    }
}
