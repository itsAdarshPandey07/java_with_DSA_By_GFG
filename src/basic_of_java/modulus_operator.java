package basic_of_java;
//modulus operator is % that only gives the remender not the remaining
public class modulus_operator {
    static void main() {
        int a=3535;
        System.out.println(a%23);
        System.out.println(a%-23);//a%(-b)=a%b
        System.out.println(-a%23);//(-a)%b=-(a%b)


    }
}
